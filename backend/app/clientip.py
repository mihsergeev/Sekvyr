"""Настоящий адрес клиента за обратным прокси.

Панель работает за цепочкой "прокси -> nginx фронтенда -> бэкенд", поэтому
`request.client.host` - это адрес соседнего контейнера, а не человека. В журнал
и в лимитер попыток входа должен попадать человек.

Считаем по числу доверенных прокси-хопов, а не по "первому публичному адресу":
админка Sekvyr живет за VPN, и адреса клиентов там как раз приватные - правило
"публичный значит настоящий" схлопнуло бы всех сотрудников в один ключ лимитера,
и один подбирающий пароль запер бы вход всей команде.

Каждый прокси дописывает в `X-Forwarded-For` адрес СВОЕГО пира, справа. Значит:

  * базовый compose (клиент -> nginx -> бэкенд)      - hops=1, клиент это XFF[-1];
  * с внешним прокси (клиент -> caddy -> nginx -> ...)  - hops=2, клиент это XFF[-2].

Все, что левее нужной позиции, могло быть подделано самим клиентом, поэтому
оттуда мы не берем ничего. Ошибаться в большую сторону нельзя: при hops больше
реального адрес берется как раз из той части заголовка, которую пишет сам
клиент, и подмена обходит и лимитер, и белые списки. Поэтому hops задается ровно
по числу прокси перед панелью (docs/install). В меньшую сторону ошибка
безопасна, но тогда все клиенты видны адресом прокси.
"""

from fastapi import Request


def client_ip(request: Request, hops: int = 1) -> str:
    raw = request.headers.get("x-forwarded-for", "")
    chain = [part.strip() for part in raw.split(",") if part.strip()]
    if chain and 1 <= hops <= len(chain):
        return chain[-hops]
    return request.client.host if request.client else "unknown"
