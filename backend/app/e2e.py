"""Проекты, значения которых сервер не видит.

Обычный проект панель шифрует сама: ключом окружения, обернутым корневым.
Компрометация распечатанной панели означает доступ к значениям - это записано в
модели угроз честно и прямо. Режим e2e закрывает именно эту дыру: значения
шифруются в браузере ключом проекта, которого у сервера нет вовсе.

Как это устроено:

  * **Ключ проекта** - 32 случайных байта, рождается в браузере.
  * **Пароль проекта** превращается в ключ-обертку (PBKDF2-SHA256, 600 000
    итераций) и запечатывает ключ проекта. Панель хранит только обертку.
  * **Для машины** ключ проекта запечатывается на её публичный ключ (ECDH
    P-256): браузер делает это сам, панель хранит результат и раскрыть его не
    может.
  * **Значения** приходят на сервер уже зашифрованными и дальше шифруются еще
    раз, обычным ключом окружения. Второй слой не лишний: он оставляет в силе
    привязку шифротекста к своему месту и всю машинерию версий.

Что панель теряет в этом режиме, и это не недоработка, а суть:

  * не может показать значение никому, кроме того, кто знает пароль проекта
    или владеет ключом машины;
  * не умеет выгружать `.env`, собирать такой проект в аварийный архив и
    переносить в него что-либо со стороны сервера;
  * не восстановит ничего, если пароль проекта забыт. Совсем ничего.

Здесь лежит только проверка формата: сама криптография живет в браузере
(`frontend/src/e2e.ts`) и в агенте. Серверу нечего расшифровывать - и в этом
весь смысл.
"""

from __future__ import annotations

import base64

# Метка, с которой начинается запечатанное браузером значение. Нужна, чтобы
# panel и агент отличали e2e-значение от обычного текста, не гадая по длине.
PREFIX = "e2e1:"
# Ниже - то, что панель проверяет у чужого шифротекста. Больше про него она не
# знает ничего и знать не должна.
MIN_LEN = 24
MAX_LEN = 200_000

# Число итераций в проекте не хранится, браузер берет его отсюда при каждом
# входе. Поменять его значит сделать "неверным" пароль всех существующих
# e2e-проектов, поэтому только вместе с полем в проекте и переходом.
PBKDF2_ITERATIONS = 600_000
# Кривая, на которой человек запечатывает ключ проекта для машины. P-256, а не
# X25519: её умеет WebCrypto во всех браузерах и стандартная библиотека Go, а
# браузер тут обязательный участник.
CURVE = "P-256"
SALT_LEN = 16
NONCE_LEN = 12


class FormatError(ValueError):
    """Пришло не то, что панель готова хранить как e2e-значение."""


def is_sealed(value: str) -> bool:
    return value.startswith(PREFIX)


def check_value(value: str) -> None:
    """Проверяет, что значение похоже на запечатанное браузером.

    Проверка нарочно поверхностная: сервер не знает ключа и не может убедиться,
    что внутри осмысленный шифротекст. Она ловит другое - попытку записать в
    e2e-проект открытый текст, случайно или по ошибке в клиенте.
    """
    if not is_sealed(value):
        raise FormatError(
            "в проект с шифрованием в браузере можно класть только запечатанные "
            "значения — панель не должна видеть открытый текст"
        )
    body = value[len(PREFIX) :]
    if not MIN_LEN <= len(body) <= MAX_LEN:
        raise FormatError("запечатанное значение не того размера")
    try:
        base64.b64decode(body, validate=True)
    except Exception as exc:  # noqa: BLE001
        raise FormatError("запечатанное значение не разбирается как base64") from exc


def check_wrap(nonce: str, ciphertext: str) -> None:
    """Обертка ключа проекта: та же поверхностная проверка формата."""
    for name, blob, limit in (("nonce", nonce, 64), ("обёртка", ciphertext, 4000)):
        if not blob or len(blob) > limit:
            raise FormatError(f"{name} не того размера")
        try:
            raw = base64.b64decode(blob, validate=True)
        except Exception as exc:  # noqa: BLE001
            raise FormatError(f"{name} не разбирается как base64") from exc
        # AES-GCM и в браузере, и в агенте - с nonce ровно 12 байт. Другой
        # длины агент на Go не открывает вовсе, а паникой ронял бы службу со
        # всеми приложениями ноды.
        if name == "nonce" and len(raw) != 12:
            raise FormatError("nonce не того размера")


def check_public_key(value: str) -> None:
    """Публичный ключ: несжатая точка P-256 (65 байт).

    32 байта тоже принимаем: столько занимает публичный ключ X25519, и закрывать
    дорогу другой кривой на уровне проверки формата незачем.
    """
    try:
        raw = base64.b64decode(value, validate=True)
    except Exception as exc:  # noqa: BLE001
        raise FormatError("публичный ключ не разбирается как base64") from exc
    if len(raw) not in (32, 65):
        raise FormatError("публичный ключ должен быть длиной 32 или 65 байт")
