"""Имя группы -> кусок адреса.

Группу человек называет по-русски ("Биллинг", "Внутренние сервисы"), а в адресе
нужен латинский кусок: ссылку пересылают в мессенджере, и процентные коды в ней
превращают понятный адрес в кашу.

Транслитерация своя, без библиотеки: таблица на тридцать строк, зато никакой
зависимости в панели, которая хранит чужие секреты.
"""

import re

_CYRILLIC = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "i", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "h", "ц": "c", "ч": "ch", "ш": "sh", "щ": "sch", "ъ": "",
    "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
    # украинские и казахские буквы встречаются в названиях команд не реже
    "і": "i", "ї": "i", "є": "e", "ґ": "g", "ә": "a", "ғ": "g", "қ": "k",
    "ң": "n", "ө": "o", "ұ": "u", "ү": "u", "һ": "h",
}

_ALLOWED = re.compile(r"[^a-z0-9-]+")


def slugify(text: str, limit: int = 64) -> str:
    """Кусок адреса из произвольного имени: строчные латинские, цифры, дефис.

    Пустая строка на выходе - это нормально: у проекта может не быть группы, и
    тогда в адресе на её месте стоит прочерк.
    """
    lowered = text.strip().lower()
    latin = "".join(_CYRILLIC.get(char, char) for char in lowered)
    slug = _ALLOWED.sub("-", latin).strip("-")
    # Дефисы подряд получаются из "Биллинг / Прод" и читаются как опечатка.
    while "--" in slug:
        slug = slug.replace("--", "-")
    return slug[:limit].strip("-")
