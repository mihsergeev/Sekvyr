"""Роли людей и их уровни.

Уровень - не украшение, на нем держатся два правила панели:

  * менять чужую учетку и выдавать роль может только тот, кто СТРОГО выше;
  * правку секрета, сделанную ролью ниже порога проекта, подтверждает роль
    выше - поэтому уровни нужны сравнимыми числами, а не набором строк.

Числа с шагом 10: между соседними ролями остается место, если однажды
понадобится вставить промежуточную, и порядок при этом не переписывается.
Машины пользовательских ролей не имеют вовсе - у них своя сущность и свое
ограничение "только чтение" (app/machines.py).
"""

OWNER = "owner"
MAINTAINER = "maintainer"
DEVELOPER = "developer"
VIEWER = "viewer"

# Порядок в словаре = порядок в интерфейсе, от старшей роли к младшей.
LEVELS: dict[str, int] = {
    OWNER: 40,
    MAINTAINER: 30,
    DEVELOPER: 20,
    VIEWER: 10,
}

TITLES: dict[str, str] = {
    OWNER: "Владелец",
    MAINTAINER: "Ответственный",
    DEVELOPER: "Разработчик",
    VIEWER: "Наблюдатель",
}

ALL = tuple(LEVELS)


def level(role: str) -> int:
    """Уровень роли. Неизвестная роль = 0, то есть ниже любой известной:
    испорченное значение в базе не должно давать прав."""
    return LEVELS.get(role, 0)


def outranks(actor_role: str, target_role: str) -> bool:
    """Может ли actor распоряжаться target'ом. Строго выше - равные роли друг
    друга не трогают: иначе два владельца могут разжаловать один другого."""
    return level(actor_role) > level(target_role)
