func adversarialFixture(t *testing.T, name string, out any) {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join("..", "..", "tests", "e2e2", name))
	if err != nil {
		t.Fatal(err)
	}
	if err := json.Unmarshal(raw, out); err != nil {
		t.Fatal(err)
	}
}

func adversarialBase64(t *testing.T, raw string) []byte {
	t.Helper()
	decoded, err := base64.RawURLEncoding.Strict().DecodeString(raw)
	if err != nil {
		t.Fatal(err)
	}
	return decoded
}

func adversarialJSON(t *testing.T, value any) []byte {
	t.Helper()
	raw, err := json.Marshal(value)
	if err != nil {
		t.Fatal(err)
	}
	return raw
}

func adversarialExpected(t *testing.T, raw []byte, hash string, public []byte) e2e2.Expected {
	t.Helper()
	var envelope e2e2.Envelope
	if err := json.Unmarshal(raw, &envelope); err != nil {
		t.Fatal(err)
	}
	header := envelope.Body.Header
	return e2e2.Expected{
		Scope: header.Scope, Sequence: header.Sequence, EnvelopeHash: hash,
		ReadKeyEpoch: header.ReadKeyEpoch, PublisherPolicyEpoch: header.PublisherPolicyEpoch,
		PublisherKeys: map[string]ed25519.PublicKey{e2e2.KeyID(public): public},
	}
}

// The attacks are generated by an independent Python implementation and signed
// by the public fixture publisher. Verify each signature with Go's standard
// Ed25519 before testing rejection, rather than accepting a bad-signature fail.
func TestAdversarialIndependentSignedSnapshotCorpus(t *testing.T) {
	var corpus struct {
		PublisherPublicKey string `json:"publisher_public_key"`
		ReadKey            string `json:"public_test_view_read_key"`
		Cases              []struct {
			Name       string          `json:"name"`
			Valid      bool            `json:"valid"`
			Envelope   json.RawMessage `json:"envelope"`
			Hash       string          `json:"envelope_hash"`
			SignedBody string          `json:"canonical_signed_body_base64url"`
			Plaintext  json.RawMessage `json:"expected_plaintext"`
		} `json:"cases"`
	}
	adversarialFixture(t, "public-snapshot-corpus.json", &corpus)
	public := adversarialBase64(t, corpus.PublisherPublicKey)
	readKey := adversarialBase64(t, corpus.ReadKey)
	if len(corpus.Cases) < 40 {
		t.Fatal("signed attack corpus missing")
	}
	baseExpected := adversarialExpected(t, corpus.Cases[0].Envelope, corpus.Cases[0].Hash, public)
	for _, item := range corpus.Cases {
		t.Run(item.Name, func(t *testing.T) {
			var envelope struct {
				Signature string `json:"signature"`
			}
			if err := json.Unmarshal(item.Envelope, &envelope); err != nil {
				t.Fatal(err)
			}
			message := append([]byte("sekvyr-e2e2/publish/v1\x00"), adversarialBase64(t, item.SignedBody)...)
			if !ed25519.Verify(public, message, adversarialBase64(t, envelope.Signature)) {
				t.Fatal("attack fixture does not have a valid publisher signature")
			}
			expected := baseExpected
			expected.EnvelopeHash = item.Hash
			verified, err := e2e2.VerifyEnvelope(item.Envelope, expected)
			if !item.Valid {
				if err != nil {
					return
				}
				if _, err = verified.Decrypt(readKey); err == nil {
					t.Fatal("accepted independently signed invalid semantics")
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			plain, err := verified.Decrypt(readKey)
			if err != nil {
				t.Fatal(err)
			}
			actual, err := e2e2.Canonical(adversarialJSON(t, plain), e2e2.MaxPlaintextBytes)
			if err != nil {
				t.Fatal(err)
			}
			want, err := e2e2.Canonical(item.Plaintext, e2e2.MaxPlaintextBytes)
			if err != nil || !bytes.Equal(actual, want) {
				t.Fatal("cross-language plaintext changed")
			}
		})
	}
}

func TestAdversarialRestrictedJCSAndParser(t *testing.T) {
	var fixture struct {
		Unicode   json.RawMessage `json:"unicode_case"`
		Canonical string          `json:"unicode_canonical_base64url"`
	}
	adversarialFixture(t, "public-reader-wrap-vector.json", &fixture)
	canonical, err := e2e2.Canonical(fixture.Unicode, 4096)
	if err != nil || !bytes.Equal(canonical, adversarialBase64(t, fixture.Canonical)) {
		t.Fatal("JCS bytes differ from Python and Node for control/HTML/astral/JS separator/decomposed strings")
	}
	for name, raw := range map[string][]byte{
		"duplicate decoded alias":  []byte(`{"a":1,"\u0061":1}`),
		"duplicate exact key":      []byte(`{"a":1,"a":1}`),
		"float token":              []byte(`{"entry_count":1.0}`),
		"exponent token":           []byte(`{"entry_count":1e0}`),
		"negative zero token":      []byte(`{"entry_count":-0}`),
		"unsafe integer":           []byte(`{"count":9007199254740992}`),
		"unpaired high surrogate":  []byte(`{"value":"\ud800"}`),
		"unpaired low surrogate":   []byte(`{"value":"\udfff"}`),
		"malformed surrogate pair": []byte(`{"value":"\ud800\u0001"}`),
		"malformed utf8":           append([]byte(`{"value":"`), 0xff, '"', '}'),
		"BOM":                      append([]byte{0xef, 0xbb, 0xbf}, []byte(`{"a":1}`)...),
		"extra json document":      []byte(`{"a":1}{"a":1}`),
		"non ASCII property":       []byte(`{"\u00e9":1}`),
		"depth":                    []byte(strings.Repeat("[", 40) + "0" + strings.Repeat("]", 40)),
	} {
		t.Run(name, func(t *testing.T) {
			if _, err := e2e2.Canonical(raw, 4096); err == nil {
				t.Fatal("invalid byte/profile input accepted")
			}
		})
	}
	if _, err := e2e2.Canonical([]byte(`{"a":1}`), 6); err == nil {
		t.Fatal("byte bound ignored")
	}
	if got, err := e2e2.Canonical([]byte(`{"value":"\ud834\udd1e"}`), 4096); err != nil || !bytes.Contains(got, []byte("𝄞")) {
		t.Fatal("valid scalar surrogate pair was not preserved")
	}
}

func TestAdversarialIndependentPublicReaderWrap(t *testing.T) {
	var fixture struct {
		Publisher  string          `json:"publisher_public_key"`
		Scalar     string          `json:"public_test_node_scalar"`
		Public     string          `json:"node_public_key"`
		ReadKey    string          `json:"public_test_view_read_key"`
		Wrap       json.RawMessage `json:"wrapper"`
		SignedBody string          `json:"canonical_wrapper_body_base64url"`
	}
	adversarialFixture(t, "public-reader-wrap-vector.json", &fixture)
	var original struct {
		Envelope json.RawMessage `json:"envelope"`
		Hash     string          `json:"envelope_hash"`
	}
	raw, err := os.ReadFile(filepath.Join("..", "..", "design", "e2e2.public-vectors.json"))
	if err != nil {
		t.Fatal(err)
	}
	if err := json.Unmarshal(raw, &original); err != nil {
		t.Fatal(err)
	}
	public := adversarialBase64(t, fixture.Publisher)
	expected := adversarialExpected(t, original.Envelope, original.Hash, public)
	verified, err := e2e2.VerifyEnvelope(original.Envelope, expected)
	if err != nil {
		t.Fatal(err)
	}
	node, err := ecdh.P256().NewPrivateKey(adversarialBase64(t, fixture.Scalar))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(node.PublicKey().Bytes(), adversarialBase64(t, fixture.Public)) {
		t.Fatal("P-256 public fixture mismatch")
	}
	var wrapper e2e2.ReaderWrap
	if err := json.Unmarshal(fixture.Wrap, &wrapper); err != nil {
		t.Fatal(err)
	}
	if !ed25519.Verify(public, append([]byte("sekvyr-e2e2/reader-wrap-sign/v1\x00"), adversarialBase64(t, fixture.SignedBody)...), adversarialBase64(t, wrapper.Signature)) {
		t.Fatal("Python wrapper signature does not verify in Go")
	}
	unwrapped, err := e2e2.UnwrapReader(fixture.Wrap, node, verified)
	if err != nil || !bytes.Equal(unwrapped, adversarialBase64(t, fixture.ReadKey)) {
		t.Fatal("Python/Node/Go ECDH+HKDF+AES-GCM wrapper mismatch")
	}
	if _, err := verified.Decrypt(unwrapped); err != nil {
		t.Fatal(err)
	}

	// Mutating caller-owned input or returned header cannot alter verified trust.
	for _, key := range expected.PublisherKeys {
		key[0] ^= 1
	}
	header := verified.Header()
	header.ProjectID = "bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb"
	if _, err := e2e2.UnwrapReader(fixture.Wrap, node, verified); err != nil {
		t.Fatal("verified state aliases caller-owned memory")
	}
	if verified.Header().ProjectID == header.ProjectID {
		t.Fatal("verified header is externally mutable")
	}

	for name, mutate := range map[string]func(*e2e2.ReaderWrap){
		"recipient": func(w *e2e2.ReaderWrap) {
			w.Body.Context.RecipientFingerprint = "p256-sha256:" + strings.Repeat("0", 64)
		},
		"view":             func(w *e2e2.ReaderWrap) { w.Body.Context.ViewID = "bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb" },
		"epoch":            func(w *e2e2.ReaderWrap) { w.Body.Context.ReadKeyEpoch = "2" },
		"publisher policy": func(w *e2e2.ReaderWrap) { w.Body.Context.PublisherPolicyEpoch = "2" },
		"ephemeral point": func(w *e2e2.ReaderWrap) {
			w.Body.EphemeralPublic = base64.RawURLEncoding.EncodeToString(make([]byte, 65))
		},
		"salt":       func(w *e2e2.ReaderWrap) { w.Body.Salt = base64.RawURLEncoding.EncodeToString(make([]byte, 32)) },
		"nonce":      func(w *e2e2.ReaderWrap) { w.Body.Nonce = base64.RawURLEncoding.EncodeToString(make([]byte, 12)) },
		"ciphertext": func(w *e2e2.ReaderWrap) { w.Body.Ciphertext = base64.RawURLEncoding.EncodeToString(make([]byte, 80)) },
		"signature":  func(w *e2e2.ReaderWrap) { w.Signature = base64.RawURLEncoding.EncodeToString(make([]byte, 64)) },
	} {
		t.Run(name, func(t *testing.T) {
			var changed e2e2.ReaderWrap
			if err := json.Unmarshal(fixture.Wrap, &changed); err != nil {
				t.Fatal(err)
			}
			mutate(&changed)
			if _, err := e2e2.UnwrapReader(adversarialJSON(t, changed), node, verified); err == nil {
				t.Fatal("wrapper substitution accepted")
			}
		})
	}
	if _, err := e2e2.UnwrapReader(fixture.Wrap, node, &e2e2.VerifiedEnvelope{}); err == nil {
		t.Fatal("zero verified envelope accepted")
	}
	if _, err := (*e2e2.VerifiedEnvelope)(nil).Decrypt(unwrapped); err == nil {
		t.Fatal("nil verification bypass")
	}
}

func TestAdversarialWireShapeHashAndEncoding(t *testing.T) {
	var original struct {
		Envelope  json.RawMessage `json:"envelope"`
		Hash      string          `json:"envelope_hash"`
		Publisher string          `json:"publisher_public_key"`
	}
	raw, err := os.ReadFile(filepath.Join("..", "..", "design", "e2e2.public-vectors.json"))
	if err != nil {
		t.Fatal(err)
	}
	if err := json.Unmarshal(raw, &original); err != nil {
		t.Fatal(err)
	}
	base := adversarialJSON(t, original.Envelope)
	public := adversarialBase64(t, original.Publisher)
	expected := adversarialExpected(t, base, original.Hash, public)
	for name, changed := range map[string][]byte{
		"float count":             bytes.Replace(base, []byte(`"entry_count":1`), []byte(`"entry_count":1.0`), 1),
		"exponent count":          bytes.Replace(base, []byte(`"entry_count":1`), []byte(`"entry_count":1e0`), 1),
		"null required count":     bytes.Replace(base, []byte(`"entry_count":1`), []byte(`"entry_count":null`), 1),
		"escaped duplicate alias": bytes.Replace(base, []byte(`"entry_count":1`), []byte(`"entry_count":1,"\u0065ntry_count":1`), 1),
		"case mismatch":           bytes.Replace(base, []byte(`"entry_count":1`), []byte(`"ENTRY_COUNT":1`), 1),
		"unknown property":        bytes.Replace(base, []byte(`"entry_count":1`), []byte(`"entry_count":1,"extra":true`), 1),
		"null parents":            bytes.Replace(base, []byte(`"parents":[]`), []byte(`"parents":null`), 1),
	} {
		t.Run(name, func(t *testing.T) {
			if bytes.Equal(base, changed) {
				t.Fatal("test mutation did not change any bytes")
			}
			if _, err := e2e2.VerifyEnvelope(changed, expected); err == nil {
				t.Fatal("invalid wire shape accepted")
			}
		})
	}
	for _, counter := range []string{"18446744073709551616", "01", "-1", "1.0", "1e0", "+1", " 1", ""} {
		if _, err := e2e2.Counter(counter, false); err == nil {
			t.Fatal("counter accepted: " + counter)
		}
	}
	if value, err := e2e2.Counter("18446744073709551615", false); err != nil || value != ^uint64(0) {
		t.Fatal("maximum uint64 rejected")
	}
	for _, encoded := range []string{"AA=", "A+", "A/", "AB", "A", "AA\n"} {
		if _, err := e2e2.DecodeBase64(encoded, -1); err == nil {
			t.Fatal("noncanonical Base64url accepted")
		}
	}
	fork := expected
	fork.EnvelopeHash = strings.Repeat("1", 64)
	if _, err := e2e2.VerifyEnvelope(base, fork); err == nil {
		t.Fatal("same sequence different canonical hash accepted")
	}
	wrongSequence := expected
	wrongSequence.Sequence = "2"
	if _, err := e2e2.VerifyEnvelope(base, wrongSequence); err == nil {
		t.Fatal("unexpected witness sequence accepted")
	}
	sum := sha256.Sum256(adversarialBase64(t, original.Publisher))
	if e2e2.KeyID(public) != "ed25519-sha256:"+hex.EncodeToString(sum[:]) {
		t.Fatal("publisher fingerprint is not standard SHA256")
	}
}

