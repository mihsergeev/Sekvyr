func TestAdversarialEd25519AndNodePublicKeyValidation(t *testing.T) {
	var fixture struct {
		Publisher string `json:"publisher_public_key"`
		Scalar    string `json:"public_test_node_scalar"`
		Public    string `json:"node_public_key"`
	}
	adversarialFixture(t, "public-reader-wrap-vector.json", &fixture)
	if !e2e2.ValidEd25519PublicKey(adversarialBase64(t, fixture.Publisher)) {
		t.Fatal("public normal Ed25519 key rejected")
	}
	identity := make([]byte, 32)
	identity[0] = 1
	negativeIdentity := bytes.Clone(identity)
	negativeIdentity[31] = 0x80
	modulus := bytes.Repeat([]byte{0xff}, 32)
	modulus[0], modulus[31] = 0xed, 0x7f
	orderTwo := bytes.Clone(modulus)
	orderTwo[0] = 0xec
	for name, key := range map[string][]byte{
		"nil": nil, "short": make([]byte, 31), "long": make([]byte, 33),
		"identity": identity, "noncanonical identity": negativeIdentity,
		"modulus": modulus, "order two": orderTwo, "order four": make([]byte, 32),
	} {
		t.Run(name, func(t *testing.T) {
			if e2e2.ValidEd25519PublicKey(key) {
				t.Fatal("noncanonical or low-order Ed25519 public key accepted")
			}
		})
	}
	node, err := ecdh.P256().NewPrivateKey(adversarialBase64(t, fixture.Scalar))
	if err != nil {
		t.Fatal(err)
	}
	fingerprint, err := e2e2.NodeKeyFingerprint(node.PublicKey())
	sum := sha256.Sum256(adversarialBase64(t, fixture.Public))
	if err != nil || fingerprint != "p256-sha256:"+hex.EncodeToString(sum[:]) {
		t.Fatal("node fingerprint differs from Python/Node")
	}
	if _, err := e2e2.NodeKeyFingerprint(nil); err == nil {
		t.Fatal("nil node public key accepted")
	}
	x25519, err := ecdh.X25519().NewPrivateKey(bytes.Repeat([]byte{1}, 32))
	if err != nil {
		t.Fatal(err)
	}
	if _, err := e2e2.NodeKeyFingerprint(x25519.PublicKey()); err == nil {
		t.Fatal("unnegotiated curve accepted")
	}
}
